#!/usr/bin/env python3
"""One definition generates the FOC bridge OD and EDS."""
from pathlib import Path
import argparse
import json

TYPES = {
    'u8': ('uint8_t', 0x0005), 'u16': ('uint16_t', 0x0006), 'u32': ('uint32_t', 0x0007),
    'i8': ('int8_t', 0x0002), 'i16': ('int16_t', 0x0003), 'i32': ('int32_t', 0x0004),
    'str': ('char', 0x0009),
}


def item(sub, name, typ, value, access='ro', pdo=''):
    return (sub, name, typ, value, access, pdo)


entries = []


def var(index, name, typ, value, access='ro', pdo=''):
    entries.append((index, name, [item(0, name, typ, value, access, pdo)], False))


def record(index, name, fields):
    entries.append((index, name, [item(0, name + '_count', 'u8', max(f[0] for f in fields))] + fields, True))


var(0x1000, 'device_type', 'u32', 0x00020192)
var(0x1001, 'error_register', 'u8', 0)
var(0x1008, 'device_name', 'str', 'NS800 FOC velocity bridge')
var(0x1014, 'emcy_cobid', 'u32', 0x81)
var(0x1017, 'heartbeat_ms', 'u16', 500, 'rw')
record(0x1018, 'identity', [item(1, 'vendor_id', 'u32', 0), item(2, 'product_code', 'u32', 0x800765),
                          item(3, 'revision', 'u32', 0x20000), item(4, 'serial', 'u32', 1)])
record(0x1200, 'sdo_server', [item(1, 'sdo_rx', 'u32', 0x601), item(2, 'sdo_tx', 'u32', 0x581)])
record(0x1400, 'rpdo_communication', [item(1, 'rpdo_cobid', 'u32', 0x201), item(2, 'rpdo_type', 'u8', 255)])
record(0x1600, 'rpdo_mapping', [item(1, 'rpdo_map_cw', 'u32', 0x60400010), item(2, 'rpdo_map_velocity', 'u32', 0x60FF0020)])
record(0x1800, 'tpdo_communication', [item(1, 'tpdo_cobid', 'u32', 0x181), item(2, 'tpdo_type', 'u8', 255),
                                   item(3, 'tpdo_inhibit', 'u16', 0), item(5, 'tpdo_event_ms', 'u16', 10)])
record(0x1A00, 'tpdo_mapping', [item(1, 'tpdo_map_sw', 'u32', 0x60410010), item(2, 'tpdo_map_velocity', 'u32', 0x606C0020)])
var(0x2000, 'motor_connected', 'u8', 1)
var(0x2001, 'rx_count', 'u32', 0)
var(0x2002, 'tx_count', 'u32', 0)
var(0x2003, 'protocol_bench', 'u8', 0)
var(0x2004, 'start_current_ma', 'u16', 800, 'rw')
var(0x2005, 'control_timeout_ms', 'u16', 500)
var(0x2006, 'foc_error', 'u32', 0)
var(0x603F, 'error_code', 'u16', 0)
var(0x6040, 'controlword', 'u16', 0, 'rw', 'rx')
var(0x6041, 'statusword', 'u16', 0x40, 'ro', 'tx')
var(0x605A, 'quick_stop_option', 'i16', 0)
var(0x6060, 'mode', 'i8', 3, 'rw')
var(0x6061, 'mode_display', 'i8', 3)
var(0x606C, 'actual_velocity', 'i32', 0, 'ro', 'tx')
var(0x60FF, 'target_velocity', 'i32', 0, 'rw', 'rx')
var(0x6502, 'supported_modes', 'u32', 4)


def generate():
    header = ['/* Generated by generate_od.py. */', '#ifndef NS800_OD_H', '#define NS800_OD_H',
              '#include "301/CO_ODinterface.h"', 'extern OD_t *OD;', 'void OD_reset(void);']
    code = ['/* Generated by generate_od.py. */', '#define OD_DEFINITION', '#include "OD.h"']
    resets, odlist = [], []
    eds = ['[FileInfo]', 'FileName=NS800_FOC_BRIDGE.eds', 'FileVersion=2', 'FileRevision=0',
           'EDSVersion=4.0', 'Description=Restricted CiA402 velocity bridge with real FOC commands',
           'CreationTime=12:00AM', 'CreationDate=10-30-2026', 'CreatedBy=NS800 project', '',
           '[DeviceInfo]', 'VendorName=Development - unassigned vendor ID', 'VendorNumber=0',
           'ProductName=NS800 FOC velocity bridge', 'ProductNumber=0x800765', 'RevisionNumber=0x20000',
           'BaudRate_1000=1', 'BaudRate_500=0', 'BaudRate_250=0', 'BaudRate_125=0',
           'SimpleBootUpSlave=1', 'SimpleBootUpMaster=0', 'Granularity=8', 'DynamicChannelsSupported=0',
           'GroupMessaging=0', 'NrOfRXPDO=1', 'NrOfTXPDO=1', 'LSS_Supported=0', '',
           '[DummyUsage]', 'Dummy0001=0', 'Dummy0002=0', 'Dummy0003=0', 'Dummy0004=0',
           'Dummy0005=0', 'Dummy0006=0', 'Dummy0007=0', '', '[Comments]', 'Lines=2',
           'Line1=Velocity units: mechanical rpm. Start +/-350..800; closed-loop speed +/-350..2500.',
           'Line2=Zero/reversal stops output; no standstill hold or acceleration profile.', '']
    for section, indices in [('MandatoryObjects', [0x1000, 0x1001, 0x1018]),
                             ('OptionalObjects', [i for i, _, _, _ in entries if i not in (0x1000, 0x1001, 0x1018) and not 0x2000 <= i < 0x6000]),
                             ('ManufacturerObjects', [i for i, _, _, _ in entries if 0x2000 <= i < 0x6000])]:
        eds += [f'[{section}]', f'SupportedObjects={len(indices)}']
        eds += [f'{n}=0x{i:04X}' for n, i in enumerate(indices, 1)] + ['']
    for index, name, fields, is_record in entries:
        defs = []
        if is_record:
            eds += [f'[{index:04X}]', f'ParameterName={name}', 'ObjectType=0x9', f'SubNumber={len(fields)}', '']
        for sub, field, typ, value, access, pdo in fields:
            ctype, dtype = TYPES[typ]
            sym = 'od_' + field
            init = json.dumps(value) if typ == 'str' else str(value)
            header += [f'extern {ctype} {sym}' + ('[];' if typ == 'str' else ';')]
            code += [f'{ctype} {sym}' + ('[]' if typ == 'str' else '') + f' = {init};']
            resets += [f'    memcpy({sym}, {init}, sizeof({sym}));' if typ == 'str' else f'    {sym} = {init};']
            attrs = ['ODA_SDO_RW' if access == 'rw' else 'ODA_SDO_R']
            if typ not in ('u8', 'i8', 'str'): attrs += ['ODA_MB']
            if typ == 'str': attrs += ['ODA_STR']
            if pdo: attrs += ['ODA_RPDO' if pdo == 'rx' else 'ODA_TPDO']
            length = f'sizeof({sym})' + (' - 1' if typ == 'str' else '')
            defs += [f'    {{&{sym}, ' + (f'{sub}, ' if is_record else '') + ' | '.join(attrs) + f', {length}}}']
            sec = f'{index:04X}sub{sub:X}' if is_record else f'{index:04X}'
            eds += [f'[{sec}]', f'ParameterName={field}', 'ObjectType=0x7', f'DataType=0x{dtype:04X}',
                    f'AccessType={access}', f'DefaultValue={value}', f'PDOMapping={int(bool(pdo))}', '']
        objtype = 'OD_obj_record_t' if is_record else 'OD_obj_var_t'
        decl = f'static {objtype} obj_{index:04x}' + ('[]' if is_record else '')
        code += [decl + (' = {\n' + ',\n'.join(defs) + '\n};' if is_record else ' = ' + defs[0].strip() + ';')]
        odlist += [f'    {{0x{index:04X}, {len(fields)}, {"ODT_REC" if is_record else "ODT_VAR"}, &obj_{index:04x}, NULL}}']
    code += ['static OD_entry_t list[] = {\n' + ',\n'.join(odlist) + ',\n    {0}\n};',
             f'static OD_t dictionary = {{{len(entries)}, list}};', 'OD_t *OD = &dictionary;',
             'void OD_reset(void) {\n' + '\n'.join(resets) + '\n}']
    header += ['#endif']
    return {'OD.h': '\n'.join(header) + '\n', 'OD.c': '\n'.join(code) + '\n',
            'NS800_FOC_BRIDGE.eds': '\n'.join(eds).rstrip() + '\n'}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for name, text in generate().items():
        path = Path(__file__).parent / name
        if args.check:
            assert path.read_text() == text, f'{name} differs; regenerate OD'
        else:
            path.write_text(text)
